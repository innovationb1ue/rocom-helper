export function multiplierColor(m: number): string {
  if (m === 0) return '#333';
  if (m < 0.5) return '#FF4444';
  if (m < 1.0) return '#FF8888';
  if (m === 1.0) return '#888888';
  if (m < 2.0) return '#88CC88';
  return '#44AA44';
}
